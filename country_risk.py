def country_crp(country):
    """Devuelve (prima_aplicada, nota). La prima aplicada es la del país menos la de EE.UU., porque la prima de
    mercado base (4,5 %) ya incluye el riesgo de EE.UU. Si el país no está en la tabla, devuelve (0.0, aviso)."""
    name = (country or "").strip()
    if not name:
        return 0.0, "País no informado por Yahoo: prima de riesgo país = 0. Si es un país emergente, cargala a mano."
    key = ALIASES.get(name, name)
    if key not in CRP:
        return 0.0, f"{name} no figura en la tabla de Damodaran: prima de riesgo país = 0. Cargala a mano si corresponde."
    applied = max(0.0, CRP[key] - US_CRP)
    return applied, f"{name}: {CRP[key]:.2%} (Damodaran) menos {US_CRP:.2%} de EE.UU. = {applied:.2%} aplicada. Fuente: {SOURCE}."
